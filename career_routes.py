from flask import Blueprint, render_template, request, redirect, url_for, flash, session
from utils.decorators import login_required
from models.career_model import CareerModel
from models.recommendation_model import RecommendationModel
from models.assessment_model import AssessmentModel
from models.roadmap_model import RoadmapModel
from models.job_model import JobModel
from services.skill_gap import SkillGapService
from services.career_recommendation import CareerRecommendationService

career_bp = Blueprint('careers', __name__, url_prefix='/careers')

@career_bp.route('/')
def list_careers():
    """Catalog of all supported career paths."""
    careers = CareerModel.get_all(active_only=True)
    return render_template('careers.html', careers=careers)


@career_bp.route('/<int:career_id>')
def career_detail(career_id):
    """Detailed career information, required competencies, roadmap, and related demonstration jobs."""
    career = CareerModel.get_by_id(career_id)
    if not career:
        flash("Career profile not found.", "warning")
        return redirect(url_for('careers.list_careers'))

    skills = CareerModel.get_skills(career_id)
    roadmap = RoadmapModel.get_by_career_id(career_id)

    # Fetch related demonstration jobs from database matching this career title
    related_jobs = JobModel.filter_jobs(keyword=career['title'].split()[0])[:4]

    return render_template(
        'career_detail.html',
        career=career,
        skills=skills,
        roadmap=roadmap,
        related_jobs=related_jobs
    )


@career_bp.route('/recommendations')
@login_required
def recommendations():
    """Personalized career recommendations generated by rule-based engine."""
    user_id = session.get('user_id')
    latest_assessment = AssessmentModel.get_latest_by_user(user_id)

    recs = []
    if latest_assessment:
        recs = RecommendationModel.get_by_assessment(latest_assessment['id'])
    else:
        # Generate on-the-fly from student profile & skills if assessment not taken yet
        recs = CareerRecommendationService.evaluate(user_id)

    return render_template('recommendations.html', recommendations=recs, assessment=latest_assessment)


@career_bp.route('/<int:career_id>/skill-gap')
@login_required
def skill_gap(career_id):
    """Deep-dive skill gap analysis comparing student's profile against a career's required skills."""
    user_id = session.get('user_id')
    analysis = SkillGapService.analyze(user_id, career_id)

    if not analysis:
        flash("Career not found for skill gap analysis.", "warning")
        return redirect(url_for('careers.list_careers'))

    return render_template('skill_gap.html', analysis=analysis)
